/**
 * Generates src/server/modules/profile/timezones.data.ts from the tzdata inside our Postgres
 * container — the same data Postgres uses to compute offsets (suggestions, Phase 8).
 *
 *   bun apps/web/scripts/gen-timezones.ts        (repo root; `bun run infra:up` first)
 *
 * Why not Intl.supportedValuesOf("timeZone"): it returns legacy ICU ids (Asia/Calcutta, not
 * Asia/Kolkata) and differs between Node and Bun. Here:
 *  - canonical zones = zone1970.tab (+ UTC),
 *  - aliases = any other zone whose compiled file is byte-identical to exactly one canonical
 *    zone (that is what a tzdata link is) → stored as the canonical name.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const script = String.raw`
cd /usr/share/zoneinfo
echo "VERSION $(apk info -v 2>/dev/null | grep '^tzdata-' | head -1)"
grep -v '^#' zone1970.tab | cut -f3 | sed 's/^/CANON /'
find . -type f ! -name '*.tab' ! -name '*.list' ! -name '*.zi' ! -path './posix/*' ! -path './right/*' \
  | sed 's|^\./||' | while read -r f; do echo "FILE $(md5sum "$f" | cut -d' ' -f1) $f"; done
`;

const out = execFileSync("docker", ["compose", "exec", "-T", "postgres", "sh", "-c", script], {
  encoding: "utf8",
  maxBuffer: 16 * 1024 * 1024,
});

let version = "unknown";
const canonical = new Set<string>(["UTC"]);
const hashOf = new Map<string, string>();
for (const line of out.split(/\r?\n/)) {
  const [kind, a, b] = line.split(" ");
  if (kind === "VERSION") version = line.slice(8).trim() || "unknown";
  else if (kind === "CANON" && a) canonical.add(a);
  else if (kind === "FILE" && a && b) hashOf.set(b, a);
}

// hash → canonical zones with that content
const canonicalByHash = new Map<string, string[]>();
for (const zone of canonical) {
  const hash = hashOf.get(zone);
  if (!hash) throw new Error(`No compiled file for canonical zone ${zone}`);
  canonicalByHash.set(hash, [...(canonicalByHash.get(hash) ?? []), zone]);
}

const aliases: Record<string, string> = {};
for (const [zone, hash] of [...hashOf].sort(([x], [y]) => x.localeCompare(y))) {
  if (canonical.has(zone)) continue;
  const targets = canonicalByHash.get(hash);
  if (targets?.length === 1) aliases[zone] = targets[0]!;
}

const zones = [...canonical].sort();
const file = `// GENERATED by apps/web/scripts/gen-timezones.ts — do not edit by hand.
// Source: ${version} (postgres:17-alpine container) — the tzdata Postgres itself uses.
// ${zones.length} canonical zones, ${Object.keys(aliases).length} aliases.

/** Canonical IANA zone names accepted and stored. */
export const CANONICAL_TIMEZONES: readonly string[] = ${JSON.stringify(zones, null, 2)};

/** Legacy / alias names → canonical name (e.g. browsers report Asia/Calcutta). */
export const TIMEZONE_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(aliases, null, 2)};
`;

const target = path.resolve(import.meta.dirname, "../src/server/modules/profile/timezones.data.ts");
writeFileSync(target, file);
console.log(
  `✔ ${zones.length} canonical zones, ${Object.keys(aliases).length} aliases (${version}) → ${target}`,
);
